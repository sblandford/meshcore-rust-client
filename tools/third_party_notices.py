LICENCE_FILE = re.compile(r"^(licen[cs]e|copying|notice|copyright|unlicense)([-_.].*)?$", re.I)


def licence_files(pkg_dir, name):
    found = []
    for entry in sorted(os.listdir(pkg_dir)):
        path = os.path.join(pkg_dir, entry)
        if os.path.isfile(path) and LICENCE_FILE.match(entry):
            found.append(path)
        elif os.path.isdir(path) and entry.lower() in ("licenses", "licences", "license"):
            found += [os.path.join(path, f) for f in sorted(os.listdir(path)) if os.path.isfile(os.path.join(path, f))]
    if name == "epaint_default_fonts":  # fonts embedded in the executable
        fonts = os.path.join(pkg_dir, "fonts")
        found += [os.path.join(fonts, f) for f in sorted(os.listdir(fonts)) if f.endswith(".txt")]
    return found


def read(path):
    with open(path, encoding="utf-8", errors="replace") as f:
        return f.read().replace("\r\n", "\n").strip()


def generate():
    meta = json.loads(subprocess.check_output(["cargo", "metadata", "--format-version", "1", "--locked"], cwd=ROOT))
    root_ids = set(meta.get("workspace_members", []))
    pkgs = sorted((p for p in meta["packages"] if p["id"] not in root_ids), key=lambda p: (p["name"].lower(), p["version"]))

    texts = defaultdict(list)  # licence text -> ["crate version (file)"]
    no_text = []
    rows = []
    for p in pkgs:
        label = f'{p["name"]} {p["version"]}'
        rows.append((label, p.get("license") or p.get("license_file") or "unspecified", p.get("repository") or ""))
        files = licence_files(os.path.dirname(p["manifest_path"]), p["name"])
        if not files:
            authors = ", ".join(re.sub(r"\s*<[^>]*>", "", a) for a in p.get("authors") or []) or "the authors"
            no_text.append((label, p.get("license") or "unspecified", authors))
        for f in files:
            texts[read(f)].append(f"{label} ({os.path.basename(f)})")

    w = max(len(r[0]) for r in rows)
    out = [
        "THIRD-PARTY SOFTWARE NOTICES",
        "Rust Desktop Client for MeshCore",
        "",
        "This application is licensed under the GNU General Public License v3.0 (see LICENSE).",
        "It includes the open-source components listed below, each under its own licence.",
        "Where a component offers a choice of licences, any of them may apply. This list covers",
        "every platform (Linux, Windows and macOS), so a given build contains only a subset.",
        "Embedded fonts (egui default fonts): Ubuntu Light (Ubuntu Font Licence 1.0),",
        "Hack (MIT / Bitstream Vera), Noto Emoji (SIL Open Font Licence 1.1), emoji-icon-font (MIT).",
        "",
        "Generated by tools/third_party_notices.py from Cargo.lock.",
        "",
        "=" * 78,
        "COMPONENTS",
        "=" * 78,
    ]
    out += [f"{name:<{w}}  {lic}" + (f"  <{repo}>" if repo else "") for name, lic, repo in rows]
    if no_text:
        out += ["", "The following components do not ship a licence file. Their licence is the SPDX expression",
                "shown; the standard texts are reproduced under STANDARD LICENCE TEXTS at the end.",
                "Copyright holders are the authors named."]
        out += [f"  {name}: {lic}; copyright (c) {authors}" for name, lic, authors in no_text]
    out += ["", "=" * 78, "LICENCE TEXTS", "=" * 78]
    for text, users in sorted(texts.items(), key=lambda kv: kv[1][0].lower()):
        out += ["", "-" * 78, "Applies to:"] + [f"  {u}" for u in users] + ["-" * 78, "", text]
    apache = next((t for t in texts if t.startswith("Apache License") and "Version 2.0, January 2004" in t and "END OF TERMS AND CONDITIONS" in t), None)
    out += ["", "=" * 78, "STANDARD LICENCE TEXTS", "=" * 78]
    for title, body in (("MIT", MIT), ("Zlib", ZLIB), ("BSL-1.0", BSL)):
        out += ["", "-" * 78, title, "-" * 78, "", body]
    if apache:
        out += ["", "-" * 78, "Apache-2.0", "-" * 78, "", apache]
    return "\n".join(out) + "\n"


def main():
    text = generate()
    if "--check" in sys.argv:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != text:
            print("THIRD-PARTY-NOTICES.txt is out of date; run tools/third_party_notices.py", file=sys.stderr)
            sys.exit(1)
        print("THIRD-PARTY-NOTICES.txt is up to date")
        return
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
